#!/usr/bin/env python3
"""Generate original synthetic music and artwork; run with FFmpeg inside Docker.

No downloaded music or commercial album covers. Demo compositions and artwork
generated by this script are made available under CC0-1.0. The script is GPLv3.
"""
import argparse
import json
from pathlib import Path
import struct
import subprocess
import zlib

ALBUMS = [
    ('The Paper Lanterns', 'A Room Full of Sun', ('Morning Windows', 'Tea Before the Rain'), (224, 151, 97)),
    ('Quiet Atlas', 'Maps for Slow Days', ('Between Two Stations', 'The Long Way Home'), (70, 126, 132)),
    ('Juniper Notes', 'Little Woodland Stories', ('The Sleepy Fox', 'A Lantern for the Moon'), (102, 132, 92)),
    ('Студия Тихий берег', 'Письма к морю', ('Тёплый свет в окне', 'Дорога домой — маленькая история о большом путешествии'), (172, 113, 125)),
    ('Evening Assembly', 'Blue Hour', ('Last Light on the Hill', 'When the City Rests'), (91, 107, 151)),
    ('Sunday Sketchbook', 'Small Things Worth Keeping', ('Polaroid Afternoon', 'One More Cup'), (190, 156, 87)),
]


def artwork(path, color, index):
    size = 512
    rows = bytearray()
    for y in range(size):
        rows.append(0)
        for x in range(size):
            light = .72 + .3 * (1 - y / size)
            ring = 125 < ((x - 265) ** 2 + (y - 238) ** 2) ** .5 < 132
            disk = (x - 265) ** 2 + (y - 238) ** 2 < 115 ** 2
            hill = y > 350 + 35 * ((x / size + index / 7) % 1)
            rgb = (238, 225, 198) if ring else ((38, 62, 59) if disk else tuple(max(0, min(255, int(v * light * (.73 if hill else 1)))) for v in color))
            rows.extend(rgb)
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)
    path.write_bytes(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 2, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(rows)) + chunk(b'IEND', b''))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', type=Path)
    parser.add_argument('--edition-only', action='store_true', help='Add one original alternate edition for Version Collector, without recreating the six base albums')
    args = parser.parse_args()
    args.destination.mkdir(parents=True, exist_ok=True)
    albums = [('Quiet Atlas', 'Maps for Slow Days — Evening Edition', ('Between Two Stations', 'The Long Way Home'), (94, 116, 136))] if args.edition_only else ALBUMS
    for index, (artist, album, tracks, color) in enumerate(albums):
        folder = args.destination / artist / album
        folder.mkdir(parents=True, exist_ok=True)
        if (folder / 'cover.png').exists():
            raise ValueError('refusing to overwrite demo artwork')
        artwork(folder / 'cover.png', color, index)
        for number, title in enumerate(tracks, 1):
            suffix = 'flac' if args.edition_only or number == 1 else 'mp3'
            output = folder / f'{number:02d} - {title}.{suffix}'
            if output.exists():
                raise ValueError('refusing to overwrite demo recordings')
            frequency = 130.8128 * 2 ** ((1 if args.edition_only else index) / 12)
            signal = f'0.055*(sin(2*PI*{frequency}*t)+0.5*sin(2*PI*{frequency*1.25}*t)+0.35*sin(2*PI*{frequency*1.5}*t))'
            command = ['ffmpeg', '-nostdin', '-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', f'aevalsrc={signal}:s=44100:d=18', '-af', 'afade=t=in:d=1,afade=t=out:st=16:d=2', '-metadata', f'artist={artist}', '-metadata', f'album_artist={artist}', '-metadata', f'album={album}', '-metadata', f'title={title}', '-metadata', f'track={number}', '-metadata', 'date=2026', '-metadata', 'genre=Original demo', '-metadata', 'comment=Original synthetic Family Music Home demonstration; CC0-1.0', *(['-ar', '96000', '-sample_fmt', 's32'] if args.edition_only else []), str(output)]
            subprocess.run(command, check=True)
    (args.destination / ('DEMO_EDITION_PROVENANCE.json' if args.edition_only else 'DEMO_PROVENANCE.json')).write_text(json.dumps({'license': 'CC0-1.0', 'commercialMusicUsed': False, 'commercialArtworkUsed': False, 'generator': 'scripts/create-demo-library.py', 'albums': len(albums), 'tracks': len(albums) * 2}, indent=2) + '\n')
    print(f'Created {len(albums) * 2} original demonstration tracks and {len(albums)} original covers.')


if __name__ == '__main__':
    main()
